#!/usr/bin/env python3
"""Builds prog.c for the Cortex-M4 with the FPU (Keil MDK, ARM Compiler 5: armcc, armlink, fromelf) into prog_bin.h,
the image the test tests/peripherals/test_armcm4.c runs in the interpreter (armcm4.c). Only when prog.c changes;
the generated prog_bin.h is in the repository (the tests need no ARM compiler).

    python tests/data/armcm4/build.py [KEIL_ARMCC_BIN]     default C:\\Keil_v5\\ARM\\ARMCC\\bin

The image: one read-only region at 0x20020000 (SRAM3 of the OpenCPU), entry armtest_run(uint32_t *out).
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
BIN = sys.argv[1] if len(sys.argv) > 1 else r'C:\Keil_v5\ARM\ARMCC\bin'
BASE = 0x20020000


def run(*args):
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode:
        sys.exit('%s\n%s%s' % (' '.join(args), r.stdout, r.stderr))
    return r.stdout


with tempfile.TemporaryDirectory() as tmp:
    obj, axf, binf = (os.path.join(tmp, n) for n in ('prog.o', 'prog.axf', 'prog.bin'))
    run(os.path.join(BIN, 'armcc'), '--cpu=Cortex-M4.fp', '--thumb', '-O2', '--c99', '--apcs=/hardfp',
        '-c', os.path.join(HERE, 'prog.c'), '-o', obj)
    run(os.path.join(BIN, 'armlink'), '--cpu=Cortex-M4.fp', '--ro-base=0x%08X' % BASE, '--entry=armtest_run',
        '--no_scanlib', '--no_startup', '--keep=prog.o(*)', '-o', axf, obj)
    run(os.path.join(BIN, 'fromelf'), '--bin', '-o', binf, axf)
    syms = run(os.path.join(BIN, 'fromelf'), '--text', '-s', axf)
    data = open(binf, 'rb').read()
m = re.search(r'armtest_run\s+0x([0-9a-fA-F]{8})', syms)
if not m:
    sys.exit('armtest_run not found')
entry = int(m.group(1), 16)
lines = ['/* Generated by build.py from prog.c (Keil ARM Compiler 5, --cpu=Cortex-M4.fp --thumb -O2 --apcs=/hardfp). */',
         '#define ARMTEST_BASE 0x%08Xu' % BASE,
         '#define ARMTEST_ENTRY 0x%08Xu      /* armtest_run, Thumb */' % entry,
         'static const unsigned char armtest_bin[%d] = {' % len(data)]
for i in range(0, len(data), 16):
    lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
lines.append('};')
open(os.path.join(HERE, 'prog_bin.h'), 'w', encoding='ascii', newline='\n').write('\n'.join(lines) + '\n')
print('prog_bin.h: %d bytes, entry 0x%08X' % (len(data), entry))
